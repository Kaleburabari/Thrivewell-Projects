================================================================================
2. PSYCHOLOGICAL DESIGN DIRECTIVE
================================================================================

ThriveWell OS must be built on psychological safety and human dignity.

Every dashboard, onboarding screen, notification, AI response, assessment,
booking page, crisis flow, video room, and admin tool must follow these principles:

A. Emotional Safety
    - The user must never feel judged, exposed, shamed, trapped, or overwhelmed.

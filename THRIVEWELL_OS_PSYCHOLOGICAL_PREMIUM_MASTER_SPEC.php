    - Screens must feel private and secure.

B. Cognitive Load Reduction
    - Break complex workflows into clear progressive steps.
    - Avoid clutter.
    - Use simple page hierarchy.
    - Use clear primary actions.
    - Use visible progress indicators.
    - Use predictable navigation.
    - Avoid unnecessary choices.

C. Trauma-Informed UX
    - Avoid aggressive red warning designs unless truly urgent.
    - Allow users to pause, save, exit, or return.
    - Avoid forced emotional disclosure.
    - Provide reassurance before sensitive questions.
    - Use consent-first interactions.
    - Provide “I need help now” escape routes where appropriate.

D. Neurodiversity Inclusion
    - ADHD-friendly layouts.
    - Dyslexia-friendly typography option.
    - Autism-friendly predictable navigation.
    - Reduced motion mode.
    - High contrast mode.
    - Sensory-safe UI.
    - Clear icon labels.
    - Avoid flashing, chaotic animation, and unpredictable movement.

E. Behavioural Science
    - Encourage progress without addiction mechanics.
    - Use streaks carefully and ethically.
    - Avoid guilt-based notifications.
    - Avoid dark patterns.
    - Use positive reinforcement.
    - Use gentle reminders.
    - Use meaningful milestone recognition.

F. Trust Formation
    - Explain why sensitive data is requested.
    - Show privacy controls clearly.
